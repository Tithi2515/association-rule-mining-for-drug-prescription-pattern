"""
eda.py
================================================================================
Exploratory Data Analysis (EDA) module for the Drug Association Rule Mining Project.
Computes frequency counts, prevalence percentages across retained mortality records,
and identifies the top co-occurring substances.
================================================================================
"""

from typing import Optional
from pathlib import Path
import pandas as pd


def compute_substance_frequencies(bool_df: pd.DataFrame) -> pd.DataFrame:
    """
    Computes absolute counts and relative percentages for each substance across
    the retained transactions.

    Parameters
    ----------
    bool_df : pd.DataFrame
        Boolean DataFrame where columns are substances and rows are transactions.

    Returns
    -------
    pd.DataFrame
        Summary DataFrame with columns:
        ['Substance', 'Frequency', 'Percentage'] sorted descending by frequency.
    """
    total_transactions = len(bool_df)
    if total_transactions == 0:
        return pd.DataFrame(columns=["Substance", "Frequency", "Percentage"])

    counts = bool_df.sum().astype(int)
    percentages = (counts / total_transactions) * 100

    freq_df = pd.DataFrame({
        "Substance": counts.index,
        "Frequency": counts.values,
        "Percentage": percentages.values,
    })

    # Sort descending by frequency
    freq_df = freq_df.sort_values(by="Frequency", ascending=False).reset_index(drop=True)
    return freq_df


def get_top_n_substances(freq_df: pd.DataFrame, n: int = 10) -> pd.DataFrame:
    """
    Extracts the top N most frequent substances from the frequency DataFrame.

    Parameters
    ----------
    freq_df : pd.DataFrame
        DataFrame generated by compute_substance_frequencies.
    n : int, default=10
        Number of top substances to extract.

    Returns
    -------
    pd.DataFrame
        Top N substances.
    """
    return freq_df.head(n).copy()


def format_frequency_table(freq_df: pd.DataFrame) -> str:
    """
    Formats the frequency DataFrame as a clean, human-readable text table.
    """
    display_df = freq_df.copy()
    display_df["Frequency"] = display_df["Frequency"].apply(lambda x: f"{x:,}")
    display_df["Percentage"] = display_df["Percentage"].apply(lambda x: f"{x:6.2f}%")
    return display_df.to_string(index=False)


def save_frequencies(freq_df: pd.DataFrame, output_path: Path) -> None:
    """
    Saves the frequency DataFrame to a CSV file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    freq_df.to_csv(output_path, index=False)
